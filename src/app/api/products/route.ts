import { NextRequest, NextResponse } from "next/server";
import { getAuthenticatedRouteDb } from "@/lib/supabase/route-db";
import { ComboRecipeItem, encodeComboRecipe } from "@/lib/products/combo-pack";
import {
  buildBaseProductSku,
  buildVariantSkusForProduct,
  extractBatchPrefix,
} from "@/lib/identifiers/codes";

function getIstTodayIso(): string {
  return new Intl.DateTimeFormat("en-CA", {
    timeZone: "Asia/Kolkata",
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  }).format(new Date());
}

interface VariantInput {
  pack_size: string;
  name: string;
  sku: string;
  cost_price: number;
  selling_price: number;
  tax_rate?: number;
  reorder_level?: number;
  opening_stock?: number;
}

export async function POST(request: NextRequest) {
  let createdProductId: string | null = null;
  let dbClient: Awaited<ReturnType<typeof getAuthenticatedRouteDb>> | null = null;

  try {
    const auth = await getAuthenticatedRouteDb();
    dbClient = auth;
    if (!auth.ok) {
      return NextResponse.json(
        { success: false, error: auth.error },
        { status: auth.status }
      );
    }

    const businessId = auth.session.businessId;
    const body = await request.json();

    const name = typeof body?.name === "string" ? body.name.trim() : "";
    const comboItems = Array.isArray(body?.combo_items)
      ? (body.combo_items as ComboRecipeItem[])
      : [];
    const hasComboRecipe = comboItems.length > 0;
    const baseSku =
      typeof body?.sku === "string" && body.sku.trim()
        ? body.sku.trim().toUpperCase()
        : buildBaseProductSku(name, { isCombo: hasComboRecipe });
    const hsn = typeof body?.hsn === "string" && body.hsn.trim() ? body.hsn.trim() : null;
    const description =
      typeof body?.description === "string" && body.description.trim()
        ? body.description.trim()
        : null;
    const categoryId =
      typeof body?.category_id === "string" && body.category_id.trim()
        ? body.category_id.trim()
        : null;
    const variants = Array.isArray(body?.variants)
      ? (body.variants as VariantInput[])
      : [];

    if (!name) {
      return NextResponse.json(
        { success: false, error: "Product name is required." },
        { status: 400 }
      );
    }

    const encodedRecipe = hasComboRecipe ? encodeComboRecipe(comboItems) : null;

    const { data: catalogSkuRows } = await auth.db
      .from("product_variants")
      .select("id, sku, product_id, products(id, name, status)")
      .eq("business_id", businessId);

    const activeCatalogSkus = new Set<string>();
    const archivedBySku = new Map<string, { id: string; sku: string }>();
    const activeBySku = new Map<string, string>();
    for (const row of (catalogSkuRows || []) as any[]) {
      const s = String(row.sku || "").trim();
      if (!s) continue;
      if (row.products?.status === "archived") {
        archivedBySku.set(s.toUpperCase(), { id: row.id, sku: s });
      } else {
        activeCatalogSkus.add(s.toUpperCase());
        activeBySku.set(s.toUpperCase(), row.products?.name || "an existing product");
      }
    }

    const autoGeneratedSkus = buildVariantSkusForProduct({
      productName: name,
      isCombo: hasComboRecipe,
      variants: variants.map((v) => ({
        pack_size: (v.pack_size || v.name || "Standard").trim(),
        name: (v.name || v.pack_size || "").trim(),
      })),
      existingCatalogSkus: activeCatalogSkus,
    });

    const resolvedSkus = variants.map((v, idx) => {
      const rawSku = (v.sku || "").trim().toUpperCase();
      if (!rawSku) return autoGeneratedSkus[idx];
      if (rawSku.startsWith("TQR-") || rawSku.startsWith(`${baseSku}-`)) return rawSku;
      if (rawSku.startsWith("-")) return `${baseSku}${rawSku}`;
      return autoGeneratedSkus[idx];
    });

    for (const skuCandidate of resolvedSkus) {
      const upper = skuCandidate.toUpperCase();
      const conflictOwner = activeBySku.get(upper);
      if (conflictOwner) {
        return NextResponse.json(
          {
            success: false,
            error: `SKU "${skuCandidate}" is already used by "${conflictOwner}". Please choose a unique variant SKU.`,
          },
          { status: 400 }
        );
      }
      const archivedMatch = archivedBySku.get(upper);
      if (archivedMatch) {
        await auth.db
          .from("product_variants")
          .update({ sku: `${archivedMatch.sku}~ARC-${Date.now().toString().slice(-6)}` })
          .eq("id", archivedMatch.id);
      }
    }

    const { data: prod, error: prodErr } = await auth.db
      .from("products")
      .insert({
        business_id: businessId,
        name,
        sku: baseSku,
        hsn,
        description,
        category_id: categoryId,
        image_url: encodedRecipe,
        status: "active",
      })
      .select()
      .single();

    if (prodErr || !prod) {
      return NextResponse.json(
        { success: false, error: prodErr?.message || "Failed to create product." },
        { status: 400 }
      );
    }

    createdProductId = prod.id;

    if (variants.length > 0) {
      const { data: taxRates } = await auth.db
        .from("tax_rates")
        .select("id, rate")
        .eq("business_id", businessId);

      const rateMap = new Map<number, string>();
      let defaultTaxRateId: string | null = null;
      for (const tr of taxRates || []) {
        rateMap.set(Number(tr.rate), tr.id);
        if (Number(tr.rate) === 18) defaultTaxRateId = tr.id;
      }

      const variantRows = variants.map((v, idx) => ({
        product_id: prod.id,
        business_id: businessId,
        name: (v.name || v.pack_size || "Standard").trim(),
        sku: resolvedSkus[idx],
        pack_size: (v.pack_size || v.name || "Standard").trim(),
        selling_price: Number(v.selling_price) || 0,
        cost_price: Number(v.cost_price) || 0,
        tax_rate_id: rateMap.get(Number(v.tax_rate ?? 18)) ?? defaultTaxRateId,
        reorder_level: Number(v.reorder_level ?? 0) || 0,
      }));

      const { data: insertedVariants, error: varErr } = await auth.db
        .from("product_variants")
        .insert(variantRows)
        .select("id, sku, pack_size, cost_price");

      if (varErr) {
        await auth.db.from("products").delete().eq("id", prod.id);
        createdProductId = null;
        return NextResponse.json(
          {
            success: false,
            error:
              varErr.code === "23505"
                ? "Duplicate variant SKU detected. Please use a unique Base SKU or suffix."
                : varErr.message,
          },
          { status: 400 }
        );
      }

      // Opening stock batches apply strictly to Single Products (Combo Packs derive stock from items)
      if (insertedVariants && !hasComboRecipe) {
        const mfgDateStr = getIstTodayIso();
        const expiry = new Date(Date.now() + 730 * 86400000);
        const expiryDateStr = expiry.toISOString().split("T")[0];

        for (let idx = 0; idx < insertedVariants.length; idx++) {
          const opening = Math.max(0, Number(variants[idx]?.opening_stock ?? 0) || 0);
          if (opening <= 0) continue;

          const variantRow = insertedVariants[idx];
          const batchPrefix = extractBatchPrefix({
            variantSku: variantRow.sku,
            productName: prod.name,
            packSize: variantRow.pack_size,
          });

          const { data: allocatedBatch, error: seqErr } = await auth.db.rpc(
            "next_batch_number",
            {
              p_business_id: businessId,
              p_variant_id: variantRow.id,
              p_prefix: batchPrefix,
              p_batch_date: mfgDateStr,
            }
          );

          if (seqErr || !allocatedBatch) {
            throw new Error(seqErr?.message || "Failed to allocate opening batch number.");
          }

          const { data: createdBatch, error: batchErr } = await auth.db
            .from("batches")
            .insert({
              business_id: businessId,
              product_variant_id: variantRow.id,
              batch_number: String(allocatedBatch),
              manufacturing_date: mfgDateStr,
              expiry_date: expiryDateStr,
              quantity_received: opening,
              cost_per_unit: Number(variantRow.cost_price) || 0,
              notes: "Opening stock recorded on product creation",
            })
            .select("id")
            .single();

          if (batchErr || !createdBatch) {
            return NextResponse.json(
              {
                success: false,
                error: batchErr?.message || "Product created, but opening stock batch failed.",
              },
              { status: 400 }
            );
          }

          const { error: movErr } = await auth.db.from("stock_movements").insert({
            business_id: businessId,
            product_variant_id: variantRow.id,
            batch_id: createdBatch.id,
            movement_type: "opening_stock",
            quantity: opening,
            reason: "Opening stock balance",
          });

          if (movErr) {
            return NextResponse.json(
              { success: false, error: movErr.message },
              { status: 400 }
            );
          }
        }
      }
    }

    return NextResponse.json({ success: true, product: prod });
  } catch (err: any) {
    if (createdProductId && dbClient?.ok) {
      await dbClient.db.from("products").delete().eq("id", createdProductId);
    }
    return NextResponse.json(
      { success: false, error: err?.message || "Failed to create product." },
      { status: 500 }
    );
  }
}

